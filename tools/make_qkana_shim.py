# -*- coding: utf-8 -*-
"""
make_qkana_shim.py — 离线替代 udkundoku 的 qkana UniDic 词典。

背景:
  udkundoku 在 import 时会执行 unidic2ud.download("qkana","unidic"),
  从 https://clrd.ninjal.ac.jp/unidic_archive/2203/UniDic-202203_60b_qkana.zip
  下载 UniDic qkana 词典。该服务器在当前网络环境 TLS 握手被重置(墙),
  导致 import 卡死。

本脚本的做法:
  用本机已装的 unidic_lite(= unidic-cwj-2.1.1 compact, PyPI 可装)的 MeCab
  词典, 复制到 unidic2ud/download/qkana/, 并写入一个自定义 dicrc, 让 MeCab
  输出 UniDic 标准的逗号分隔 29 列格式(与 qkana 同代 UniDic 的输出列序一致),
  使 udkundoku.katsuyo_verb 等函数按标准列号取值不越界。

  这是"替代词典", 不是官方 qkana(qkana 是假名见出し, 本 shim 是汉字见出し的
  cwj 精简版)。对 udkundoku 的活用表查询兜底路径有效, 但个别词的送り仮名
  推断可能与官方 qkana 不同。后续如能从官方源拿到真正的 qkana, 直接解压覆盖
  本目录即可(目录名不变)。

用法:
  python -I tools/make_qkana_shim.py          # 已存在则跳过
  python -I tools/make_qkana_shim.py --force  # 重建
"""
import os
import shutil
import sys

import unidic_lite

SRC = unidic_lite.DICDIR  # unidic_lite 的 MeCab 词典目录
PKG = os.path.dirname(os.path.dirname(os.path.abspath(unidic_lite.__file__)))
DST = os.path.join(PKG, "unidic2ud", "download", "qkana")

# unidic_lite 内部特征号 (见其 dicrc 注释):
#   f[0..3]=pos1..4 f[4]=cType f[5]=cForm f[6]=lForm f[7]=lemma f[8]=orth
#   f[9]=pron f[10]=orthBase f[11]=pronBase f[12]=goshu f[13]=iType f[14]=iForm
#   f[15]=fType f[16]=fForm f[17]=kana f[18]=kanaBase f[19]=form f[20]=formBase
#   f[21]=iConType f[22]=fConType f[23]=aType f[24]=aConType f[25]=aModType
# UniDic 标准输出列序(29 列):
#   1 pos1 .. 4 pos4, 5 cType, 6 cForm, 7 lForm, 8 lemma, 9 orth, 10 pron,
#   11 orthBase, 12 pronBase, 13 goshu, 14 iType, 15 iForm, 16 fType, 17 fForm,
#   18 iConType, 19 fConType, 20 lType, 21 kana, 22 kanaBase, 23 form,
#   24 formBase, 25 aType, 26 aConType, 27 aModType, 28 lid, 29 lemma_id
# unidic_lite 无 lType/lid/lemma_id, 对应列留空。
DICRC = """; qkana shim dicrc (generated by kanbun-kakikudashi/tools/make_qkana_shim.py)
; emits UniDic-standard comma-separated columns from unidic_lite's feature layout.
cost-factor = 700
bos-feature = BOS/EOS,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*
output-format-type = unidic
node-format-unidic = %m\\t%f[0],%f[1],%f[2],%f[3],%f[4],%f[5],%f[6],%f[7],%f[8],%f[9],%f[10],%f[11],%f[12],%f[13],%f[14],%f[15],%f[16],%f[21],%f[22],,%f[17],%f[18],%f[19],%f[20],%f[23],%f[24],%f[25],,\\n
unk-format-unidic  = %m\\t名詞,普通名詞,*,*,*,*,%m,%m,%m,%m,%m,%m,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,*,\\n
bos-format-unidic  =
eos-format-unidic  = EOS\\n
"""


def main():
    force = "--force" in sys.argv
    if os.path.isdir(DST) and not force:
        print("qkana shim already exists:", DST)
        return 0
    os.makedirs(DST, exist_ok=True)
    n = 0
    for f in os.listdir(SRC):
        if f == "dicrc":  # 用自定义格式替换
            continue
        src = os.path.join(SRC, f)
        if os.path.isfile(src):
            shutil.copy2(src, os.path.join(DST, f))
            n += 1
    with open(os.path.join(DST, "dicrc"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(DICRC)
    print("copied %d files into %s + custom dicrc" % (n, DST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
