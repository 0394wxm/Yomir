# 左传 3 公年页：抓取实证为「== 訓読文 ==」单轨（【經】【傳】皆書き下し、原文段無）
# → 不入成对样本；可抓量按 0 对计（报告中如实记录）。

PUNCT = "，。：；？！「」『』〈〉《》〔〕（）［］“”‘’、・—…∼＿*_※"


def norm(s):
    s = re.sub(r"〔[^〕]*〕", "", s or "")   # ママ/校注タグ
    s = re.sub(r"[＃＊]", "", s)
    s = re.sub(r"\s+", "", s)
    return "".join(c for c in s if c not in PUNCT)


def main():
    golden = json.load(open(os.path.join(EV, "golden_8165.json"), encoding="utf-8"))
    gset = {}
    for g in golden:
        gset[norm(g["hakubun"])] = g["id"]
    print("golden_8165: %d 条（norm 白文 unique %d）" % (len(golden), len(gset)))
    hit = 0
    for sid, hb in SAMPLES:
        h = norm(hb)
        if h in gset:
            hit += 1
            print("  重合 %-22s -> %s" % (sid, gset[h]))
    print("样本 %d 条 / 重合 %d 条 = %.1f%%" % (len(SAMPLES), hit, 100.0 * hit / len(SAMPLES)))

    out = os.path.join(EV, "night69_overlap_probe.json")
    json.dump({"samples": [{"id": sid, "hakubun": hb, "norm": norm(hb),
                            "hit_id": gset.get(norm(hb))} for sid, hb in SAMPLES],
               "n": len(SAMPLES), "hits": hit,
               "rate": round(100.0 * hit / len(SAMPLES), 1)},
              open(out, "w", encoding="utf-8", newline="\n"), ensure_ascii=False, indent=1)
    print("written:", out)


