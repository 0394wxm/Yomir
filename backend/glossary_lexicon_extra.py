    for w, r, m in VERBS:
        rows.append({"word": w, "reading": r, "meaning": m, "kind": "content"})
    for w, r, m in MODIFIERS:
        rows.append({"word": w, "reading": r, "meaning": m, "kind": "content"})
    for w, r, m in FUNCTION:
        rows.append({"word": w, "reading": r, "meaning": m, "kind": "function"})
    return rows


